"""Ticketing port: only operations the agent already uses today."""
from __future__ import annotations

from typing import Protocol, runtime_checkable

from app.ports.models import Ticket

CAP_WORK_NOTES = "work_notes"          # if absent, adapters fall back to comments
CAP_CREATE = "create"
CAP_CALLER_SEARCH = "caller_search"
CAP_SLA = "sla"
CAP_REVIEW = "review" 


@runtime_checkable
class TicketingPort(Protocol):
    provider: str
    capabilities: frozenset
    role: str  

    def list_queue(self) -> list[str]: ...
    def get(self, ticket_id: str) -> Ticket: ...
    def claim(self, ticket_id: str, note: str | None = None) -> Ticket: ...
    def add_note(self, ticket_id: str, note: str) -> None: ...
    def resolve(self, ticket_id: str, close_notes: str) -> Ticket: ...
    def escalate(self, ticket_id: str, reason: str) -> Ticket: ...
    def create(self, title: str, description: str, urgency: int = 3, impact: int = 3,
               caller: str = "", host: str = "") -> Ticket: ...
    def search_callers(self, text: str, limit: int = 8) -> list[dict]: ...
    def get_sla(self, ticket_id: str) -> dict: ...
    def ping(self) -> None: ...                                  # raises if the system is unreachable
    def open_tickets(self, caller: str, host: str = "", ticket_id: str = "",
                     limit: int = 3) -> list[Ticket]: ...
    def cancel(self, ticket_id: str, note: str) -> None: ...
    def set_severity(self, ticket_id: str, urgency: int, impact: int, note: str) -> None: ...
    def close(self, ticket_id: str, note: str) -> None: ...      # reviewer: Resolved -> Closed
    def reopen(self, ticket_id: str, note: str, group: str = "") -> None: ...   # reviewer